const std = @import("std");
const ForkSeq = @import("config").ForkSeq;
const Handler = @import("../runner/operations.zig").Handler;

pub const handlers = std.enums.values(Handler);

pub const header =
    \\// This file is generated by write_spec_tests.zig.
    \\// Do not commit changes by hand.
    \\
    \\const std = @import("std");
    \\const ForkSeq = @import("config").ForkSeq;
    \\const active_preset = @import("preset").active_preset;
    \\const spec_test_options = @import("spec_test_options");
    \\const Operations = @import("../runner/operations.zig");
    \\
    \\const allocator = std.testing.allocator;
    \\
    \\
;

const test_template =
    \\test "{s} operations {s} {s}" {{
    \\    const test_dir_name = try std.fs.path.join(allocator, &[_][]const u8{{
    \\        spec_test_options.spec_test_out_dir,
    \\        spec_test_options.spec_test_version,
    \\        @tagName(active_preset) ++ "/tests/" ++ @tagName(active_preset) ++ "/{s}/operations/{s}/pyspec_tests/{s}",
    \\    }});
    \\    defer allocator.free(test_dir_name);
    \\    const test_dir = std.Io.Dir.openDir(.cwd(), std.testing.io, test_dir_name, .{{}}) catch |err| switch (err) {{
    \\        error.FileNotFound => return error.SkipZigTest,
    \\        else => return err,
    \\    }};
    \\    defer test_dir.close(std.testing.io);
    \\
    \\    try Operations.TestCase(.{s}, .{s}).execute(allocator, test_dir);
    \\}}
    \\
    \\
;

/// PQ vectors that store a preregistration. Its signature is a stub, which the
/// spec's reference accepts with XMSS switched off, and block processing
/// always checks it: its validity decides the post-state.
const pq_stub_preregistrations = [_][]const u8{
    "max_preregistration_requests",
    "parent_payload_preregistration_stored",
    "preregistration_admitted_when_full_of_expired_records",
    "preregistration_replaces_expired_binding",
    "preregistration_stored",
};

pub fn writeHeader(writer: *std.Io.Writer) !void {
    try writer.print(header, .{});
}

pub fn writeTest(
    writer: *std.Io.Writer,
    fork: ForkSeq,
    handler: Handler,
    test_case_name: []const u8,
) !void {
    if (fork == .pq) {
        for (pq_stub_preregistrations) |name| {
            if (std.mem.eql(u8, name, test_case_name)) return;
        }
    }
    try writer.print(test_template, .{
        @tagName(fork),
        @tagName(handler),
        test_case_name,

        @tagName(fork),
        @tagName(handler),
        test_case_name,

        @tagName(fork),
        @tagName(handler),
    });
}
