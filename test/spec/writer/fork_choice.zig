const std = @import("std");
const ForkSeq = @import("config").ForkSeq;
const Handler = @import("../runner/fork_choice.zig").Handler;

pub const handlers = std.enums.values(Handler);

pub const header =
    \\// This file is generated by write_spec_tests.zig.
    \\// Do not commit changes by hand.
    \\
    \\const std = @import("std");
    \\const test_case = @import("../test_case.zig");
    \\const ForkSeq = @import("config").ForkSeq;
    \\const active_preset = @import("preset").active_preset;
    \\const spec_test_options = @import("spec_test_options");
    \\const ForkChoice = @import("../runner/fork_choice.zig");
    \\
    \\const allocator = std.testing.allocator;
    \\const pool_size = if (active_preset == .mainnet) 10_000_000 else 1_000_000;
    \\
;

const test_template =
    \\test "{s} fork_choice {s} {s}" {{
    \\    const pool = try test_case.acquirePool(allocator, pool_size);
    \\    defer test_case.releasePool();
    \\    const test_dir_name = try std.fs.path.join(allocator, &[_][]const u8{{
    \\        spec_test_options.spec_test_out_dir,
    \\        spec_test_options.spec_test_version,
    \\        @tagName(active_preset) ++ "/tests/" ++ @tagName(active_preset) ++ "/{s}/fork_choice/{s}/pyspec_tests/{s}",
    \\    }});
    \\    defer allocator.free(test_dir_name);
    \\    const test_dir = std.Io.Dir.openDir(.cwd(), std.testing.io, test_dir_name, .{{}}) catch |err| switch (err) {{
    \\        error.FileNotFound => return error.SkipZigTest,
    \\        else => return err,
    \\    }};
    \\    defer test_dir.close(std.testing.io);
    \\
    \\    try ForkChoice.TestCase(.{s}).execute(allocator, pool, test_dir, .{{}});
    \\}}
    \\
    \\
;

const skip_template =
    \\// Skipped: {s}
    \\test "{s} fork_choice {s} {s}" {{
    \\    return error.SkipZigTest;
    \\}}
    \\
    \\
;

/// Vectors whose expected rejection can only come from KZG proof verification,
/// which the Zig build has no binding for yet.
fn skipReason(test_case_name: []const u8) ?[]const u8 {
    const kzg_cases = [_][]const u8{
        "invalid_incorrect_proof",
        "on_block_peerdas__invalid_wrong_column",
        "on_block_peerdas__invalid_wrong_commitment",
        "on_block_peerdas__invalid_wrong_proof",
    };
    for (kzg_cases) |prefix| {
        if (std.mem.startsWith(u8, test_case_name, prefix)) return "needs KZG proof verification";
    }
    return null;
}

pub fn writeHeader(writer: *std.Io.Writer) !void {
    try writer.print(header, .{});
}

pub fn writeTest(
    writer: *std.Io.Writer,
    fork: ForkSeq,
    handler: Handler,
    test_case_name: []const u8,
) !void {
    if (skipReason(test_case_name)) |reason| {
        try writer.print(skip_template, .{ reason, @tagName(fork), @tagName(handler), test_case_name });
        return;
    }
    try writer.print(test_template, .{
        @tagName(fork),
        @tagName(handler),
        test_case_name,

        @tagName(fork),
        @tagName(handler),
        test_case_name,

        @tagName(fork),
    });
}
