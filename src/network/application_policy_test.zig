const std = @import("std");
const policy = @import("application_policy.zig");
const limits = @import("gossip_limits.zig");
const p = @import("preset").preset;

test "application IDONTWANT threshold follows the preset independently of chain timing" {
    const expected: usize = if (preset.active_preset == .minimal) 1462 else 16829;
    for ([_]*const config.BeaconConfig{ &config.mainnet.config, &config.minimal.config, &config.gnosis.config }) |beacon| {
        const gossip = try policy.gossip(&beacon.chain, 16);
        try std.testing.expectEqual(expected, gossip.idontwant_min_data_size);
    }
}

test "application policy bounds validator-driven work and execution shares" {
    for ([_]u64{ 1, 16, 1_000_000, 3_000_000, 9007199254740991 }) |validators| {
        const processor = try policy.processor(&.{}, validators);
        try std.testing.expect(limits.items(&processor) <= limits.capacity_max);
        const execution = try policy.execution(&.{}, &processor, .{});
        for (processor, execution) |queued, running| {
            try std.testing.expect(running.items > 0 and running.items <= queued.items);
        }
        const gossip = try policy.gossip(&config.mainnet.config.chain, validators);
        try std.testing.expectEqual(12_000 * p.SLOTS_PER_EPOCH * 2, gossip.seen_ttl_ms);
    }
    const processor = try policy.processor(&.{}, 16);
    try std.testing.expectError(error.InvalidGossipExecutionLimits, policy.execution(&.{}, &processor, .{ .items = 1 }));
    const invalid = config.mainnet.config.chain.merge(.{ .SLOT_DURATION_MS = 0 });
    try std.testing.expectError(error.InvalidNetworkConfig, policy.gossip(&invalid, 16));
    try std.testing.expectError(error.InvalidNetworkConfig, policy.gossip(&config.mainnet.config.chain, 0));
}

test "application seen retention covers the longest scheduled slot duration" {
    for ([_]u64{ 0, 20, std.math.maxInt(u64) }) |epoch| {
        for ([_]u64{ 6000, 24000 }) |duration_ms| {
            const configured = config.mainnet.config.chain.merge(.{ .HEZE_FORK_EPOCH = epoch, .SLOT_DURATION_MS_HEZE = duration_ms });
            const gossip = try policy.gossip(&configured, 16);
            const max_slot_ms = if (epoch == std.math.maxInt(u64)) 12_000 else @max(12_000, duration_ms);
            try std.testing.expectEqual(max_slot_ms * p.SLOTS_PER_EPOCH * 2, gossip.seen_ttl_ms);
            try std.testing.expectEqual(12_000, gossip.score_params.decay_interval_ms);
        }
    }
    for ([_]u64{ 0, 20, std.math.maxInt(u64) }) |epoch| {
        for ([_]u64{ 0, 86_400_001, std.math.maxInt(u64) }) |duration_ms| {
            const invalid = config.mainnet.config.chain.merge(.{ .HEZE_FORK_EPOCH = epoch, .SLOT_DURATION_MS_HEZE = duration_ms });
            try std.testing.expectError(error.InvalidNetworkConfig, policy.gossip(&invalid, 16));
        }
    }
}

const score = @import("gossipsub/score.zig");
const topics = @import("gossipsub/topic_policy.zig");
const preset = @import("preset");

// Generated by Lodestar's test/utils/nativePolicyFixtures.ts from its production score formulas.
test "application score policy matches Lodestar across committee boundaries and slot durations" {
    const Fixture = struct {
        validators: u64,
        slot_ms: u64,
        slots_per_epoch: u64,
        retained_score_ms: u64,
        global: score.Params,
        topics: [topics.kind_count]score.TopicPolicy,
    };
    const input = if (preset.active_preset == .mainnet) @embedFile("testdata/application_scores_mainnet.json") else @embedFile("testdata/application_scores_minimal.json");
    const parsed = try std.json.parseFromSlice([]Fixture, std.testing.allocator, input, .{});
    defer parsed.deinit();
    for (parsed.value) |fixture| {
        try std.testing.expectEqual(p.SLOTS_PER_EPOCH, fixture.slots_per_epoch);
        const configured = config.mainnet.config.chain.merge(.{ .SLOT_DURATION_MS = fixture.slot_ms });
        const actual = try policy.gossip(&configured, fixture.validators);
        try std.testing.expectEqual(fixture.retained_score_ms, actual.retained_score_ms);
        inline for (std.meta.fields(score.Params)) |field| {
            if (field.type == f64) {
                try std.testing.expectApproxEqRel(@field(fixture.global, field.name), @field(actual.score_params, field.name), 1e-10);
            } else if (field.type != score.TopicParams) {
                try std.testing.expectEqual(@field(fixture.global, field.name), @field(actual.score_params, field.name));
            }
        }
        for (fixture.topics, actual.topic_params.?) |expected, got| {
            try std.testing.expectEqual(expected.mesh_delivery_start_slot, got.mesh_delivery_start_slot);
            inline for (std.meta.fields(score.TopicParams)) |field| {
                if (field.type == f64) {
                    try std.testing.expectApproxEqRel(@field(expected.params, field.name), @field(got.params, field.name), 1e-10);
                } else {
                    try std.testing.expectEqual(@field(expected.params, field.name), @field(got.params, field.name));
                }
            }
            if (got.mesh_delivery_start_slot > 0) {
                try std.testing.expectEqual(0, got.atSlot(got.mesh_delivery_start_slot - 1).mesh_delivery_weight);
                try std.testing.expectEqual(got.params.mesh_delivery_weight, got.atSlot(got.mesh_delivery_start_slot).mesh_delivery_weight);
            }
        }
    }
}

const config = @import("config");
const chain = @import("chain.zig");

test "application resource policy preserves legacy queues while sharing the execution budget with Gloas" {
    if (preset.active_preset != .mainnet) return error.SkipZigTest;
    const KindLimits = struct { processor: limits.Limit, execution: limits.Limit };
    const Fixture = struct { network: enum { mainnet, hoodi }, validators: u64, limits: std.json.ArrayHashMap(KindLimits) };
    // Captured from the host configuration's mainnet/Hoodi snapshots before moving its derivation.
    const parsed = try std.json.parseFromSlice([]Fixture, std.testing.allocator, @embedFile("testdata/application_limits_mainnet.json"), .{});
    defer parsed.deinit();
    for (parsed.value) |*fixture| {
        const beacon = switch (fixture.network) {
            .mainnet => &config.mainnet.config,
            .hoodi => &config.hoodi.config,
        };
        const network = try chain.Config.init(beacon, true);
        const boundaries = network.topics[0..network.boundary_count];
        const processing = try policy.processor(boundaries, fixture.validators);
        const execution = try policy.execution(boundaries, &processing, .{});
        inline for (std.meta.fields(topics.Kind), 0..) |field, k| {
            if (fixture.limits.map.get(field.name)) |expected| {
                try std.testing.expectEqualDeep(expected.processor, processing[k]);
                try std.testing.expect(execution[k].items <= expected.execution.items);
                try std.testing.expect(execution[k].bytes <= expected.execution.bytes);
            }
        }
    }
}

test "application Gloas shares admit every configured topic maximum within the total budget" {
    var input = if (preset.active_preset == .minimal) config.minimal.chain_config else config.mainnet.chain_config;
    input.ALTAIR_FORK_EPOCH = 0;
    input.BELLATRIX_FORK_EPOCH = 0;
    input.CAPELLA_FORK_EPOCH = 0;
    input.DENEB_FORK_EPOCH = 0;
    input.ELECTRA_FORK_EPOCH = 0;
    input.FULU_FORK_EPOCH = 0;
    input.GLOAS_FORK_EPOCH = 0;
    input.BLOB_SCHEDULE = &.{};
    input.MAX_PAYLOAD_SIZE = @import("gossipsub/constants.zig").MAX_PAYLOAD_SIZE;
    const beacon = config.BeaconConfig.init(input, @splat(0));
    const derived = try chain.Config.init(&beacon, true);
    const boundaries = derived.topics[0..derived.boundary_count];
    const processing = try policy.processor(boundaries, 1_000_000);
    const budget: policy.Execution = .{};
    const execution = try policy.execution(boundaries, &processing, budget);
    try std.testing.expect(limits.bytes(&execution) <= budget.bytes);
    try std.testing.expect(limits.items(&execution) <= budget.items);
    for (boundaries) |boundary| for (boundary.rules, execution) |rule, share| {
        try std.testing.expect(share.bytes >= rule.ssz_max);
    };
}
